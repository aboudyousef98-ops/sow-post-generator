// Regenerate src/lib/aluminumWiringData.ts from Othman's aluminum-wiring xlsx.
//
//   node scripts/import-aluminum-xlsx.mjs "<path to Aluminum_Wiring_Requirements_by_Jurisdiction.xlsx>"
//
// Deterministic and loud, per the house parser rule: a blank cell, a duplicate
// jurisdiction (after "City of" stripping), or an unexpected header aborts the
// run — nothing half-generated is ever written.

import ExcelJS from 'exceljs';
import { writeFileSync } from 'node:fs';
import { basename } from 'node:path';

const src = process.argv[2];
if (!src) {
  console.error('Usage: node scripts/import-aluminum-xlsx.mjs <xlsx path>');
  process.exit(1);
}

const key = (s) =>
  s
    .trim()
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .replace(/^(city|town|village) of /, '');

const wb = new ExcelJS.Workbook();
await wb.xlsx.readFile(src);
const ws = wb.worksheets[0];

const header = ws.getRow(1).values;
if (String(header[1]).trim() !== 'Jurisdiction' || String(header[2]).trim() !== 'Aluminum Requirement') {
  console.error(`Unexpected header row: ${JSON.stringify(header)} — is this the right sheet?`);
  process.exit(1);
}

const entries = [];
const seenFull = new Map();
const seenBare = new Map();
for (let r = 2; r <= ws.rowCount; r++) {
  const v = ws.getRow(r).values;
  const name = String(v[1] ?? '').trim();
  const requirement = String(v[2] ?? '').trim();
  if (!name && !requirement) continue; // trailing blank row
  if (!name || !requirement) {
    console.error(`Row ${r}: blank ${name ? 'requirement' : 'jurisdiction'} — aborting.`);
    process.exit(1);
  }
  const full = name.toLowerCase().replace(/\s+/g, ' ');
  if (seenFull.has(full)) {
    console.error(`Row ${r}: duplicate jurisdiction "${name}" — aborting.`);
    process.exit(1);
  }
  seenFull.set(full, name);
  const k = key(name);
  if (seenBare.has(k)) {
    // e.g. "City of Lakeside" vs "Town of Lakeside" — two real jurisdictions.
    // matchAluminum treats the bare name as ambiguous; just surface it here.
    console.warn(`Row ${r}: "${name}" and "${seenBare.get(k)}" share the bare name "${k}" — exact spellings required to match.`);
  } else {
    seenBare.set(k, name);
  }
  entries.push({ name, requirement });
}

const out = `// GENERATED by scripts/import-aluminum-xlsx.mjs — do not hand-edit.
// Source: ${basename(src)} (${entries.length} jurisdictions).
// Regenerate: node scripts/import-aluminum-xlsx.mjs "<xlsx path>"

import type { AluminumEntry } from './aluminumWiring';

export const ALUMINUM_WIRING: AluminumEntry[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(new URL('../src/lib/aluminumWiringData.ts', import.meta.url), out);
console.log(`Wrote src/lib/aluminumWiringData.ts — ${entries.length} jurisdictions.`);
